import json

def parse_int(text, min_value=None, max_value=None):
  entered_int_value = int(text) # converting the text to an integer
  if min_value is not None and entered_int_value <min_value:
    raise ValueError(f"Entered value {entered_int_value} is less than min value {min_value}")
  if max_value is not None and entered_int_value > max_value:
    raise ValueError(f"Entered value {entered_int_value} is more than max_value {max_value}")
  return entered_int_value

